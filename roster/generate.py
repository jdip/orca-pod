#!/usr/bin/env python3
"""Render roster/roles.toml into native Claude and Codex agents, the SEC profile and skills/roster tables."""
import argparse
import json
import os
from pathlib import Path
import re
import sys
import tomllib

ROOT = Path(__file__).resolve().parent.parent
ROLES = ROOT / 'roster' / 'roles.toml'
SKILL = ROOT / 'skills' / 'roster' / 'SKILL.md'
ROLES_MD = ROOT / 'skills' / 'roster' / 'roles.md'
DEFAULT_OUT = ROOT / 'build' / 'roster'
BEGIN = '<!-- roster:roles:begin (generated by roster/generate.py from roster/roles.toml; do not edit) -->'
END = '<!-- roster:roles:end -->'
NOTICE = 'Generated by orca-pod roster/generate.py from roster/roles.toml; do not edit.'

PROVIDERS = {'claude', 'codex'}
EFFORTS = {'low', 'medium', 'high', 'xhigh', 'max'}
LAYERS = {'pane', 'native', 'orca'}
AUTHORITIES = {'read-only', 'write-owned-files', 'named-git-action'}
SANDBOXES = {'read-only', 'workspace-write'}
READ_ONLY_CLAUDE_TOOLS = 'Edit, Write, NotebookEdit'
NAME = re.compile(r'[a-z0-9][a-z0-9-]*')  # Role ids and profiles become file names under --out.
TOML_CONTROL = re.compile(r'[\x00-\x08\x0a-\x1f\x7f]')  # Forbidden raw in TOML basic strings; tab is allowed.


def fail(message):
    raise SystemExit(f'roles.toml: {message}')


def refuse(path, reason):
    raise SystemExit(f'generate.py: refusing to write {path}: {reason}; nothing was written')


def require(table, key, where, allowed=None):
    value = table.get(key)
    if not isinstance(value, str) or not value.strip():
        fail(f'{where} needs a non-empty string {key!r}')
    if allowed is not None and value not in allowed:
        fail(f'{where} {key} {value!r} is not one of {sorted(allowed)}')
    return value


def check_model(entry, where, sandbox):
    provider = require(entry, 'provider', where, PROVIDERS)
    require(entry, 'model', where)
    require(entry, 'effort', where, EFFORTS)
    if sandbox:
        if provider == 'codex':
            require(entry, 'sandbox', where, SANDBOXES)
        elif 'sandbox' in entry:
            fail(f'{where} sets sandbox for a Claude model')


def load(path=ROLES):
    with path.open('rb') as handle:
        roles = tomllib.load(handle).get('role')
    if not roles:
        fail('no [[role]] tables')
    seen = set()
    for role in roles:
        rid = require(role, 'id', 'a role')
        if not NAME.fullmatch(rid):
            fail(f'role id {rid!r} is not a safe name ({NAME.pattern})')
        if rid in seen:
            fail(f'duplicate role id {rid!r}')
        seen.add(rid)
        for key in ('tag', 'emoji', 'purpose', 'standing_instructions'):
            require(role, key, rid)
        require(role, 'layer', rid, LAYERS)
        require(role, 'authority', rid, AUTHORITIES)
        if not role.get('models'):
            fail(f'{rid} needs at least one [[role.models]]')
        for entry in role['models']:
            check_model(entry, f'{rid} model', sandbox=True)
        for entry in role.get('alternates', []):
            require(entry, 'when', f'{rid} alternate')
            check_model(entry, f'{rid} alternate', sandbox=False)
        if ('profile' in role) != ('launch' in role):
            fail(f'{rid} must set profile and launch together')
        if 'launch' in role:
            require(role, 'launch', rid, {'terminal'})
            if not NAME.fullmatch(require(role, 'profile', rid)):
                fail(f'{rid} profile {role["profile"]!r} is not a safe name ({NAME.pattern})')
            if [entry['provider'] for entry in role['models']] != ['codex']:
                fail(f'{rid} terminal launch needs exactly one Codex model')
    return roles


def label(role):
    return f'{role["emoji"]} {role["tag"]}'


def model_text(entry):
    return f'{entry["provider"].capitalize()} · `{entry["model"]}` · {entry["effort"]}'


def instructions(role):
    return role['standing_instructions'].strip()


def has_native_file(role):
    # The coordinator is the pane itself; a terminal-launched role must not gain a native route without its profile.
    return role['layer'] != 'pane' and 'launch' not in role


def toml_escape(value, newlines=False):
    escaped = value.replace('\\', '\\\\').replace('"', '\\"')
    return TOML_CONTROL.sub(lambda m: m[0] if newlines and m[0] == '\n' else f'\\u{ord(m[0]):04x}', escaped)


def toml_string(value):
    return f'"{toml_escape(value)}"'


def toml_multiline(value):
    return f'"""\n{toml_escape(value, newlines=True)}"""'


def claude_agent(role, entry):
    lines = [
        '---',
        f'# {NOTICE}',
        f'name: {role["id"]}',
        f'description: {json.dumps(label(role) + ": " + role["purpose"], ensure_ascii=False)}',  # A YAML double-quoted scalar.
        f'model: {entry["model"]}',
        f'effort: {entry["effort"]}',
    ]
    if role['authority'] == 'read-only':
        lines.append(f'disallowedTools: {READ_ONLY_CLAUDE_TOOLS}')
    lines += ['---', '', instructions(role), '']
    return '\n'.join(lines)


def codex_agent(role, entry):
    fields = {
        'name': role['id'],
        'description': label(role) + ': ' + role['purpose'],
        'model': entry['model'],
        'model_reasoning_effort': entry['effort'],
        'sandbox_mode': entry['sandbox'],
    }
    text = '\n'.join([
        f'# {NOTICE}',
        *(f'{key} = {toml_string(value)}' for key, value in fields.items()),
        '',
        f'developer_instructions = {toml_multiline(instructions(role))}',
        '',
    ])
    if tomllib.loads(text) != {**fields, 'developer_instructions': instructions(role)}:
        fail(f'{role["id"]} does not survive TOML rendering')
    return text


def codex_profile(role):
    (entry,) = role['models']
    return '\n'.join([
        f'# {NOTICE}',
        f'# Launch with: codex --profile {role["profile"]}',
        f'model = {toml_string(entry["model"])}',
        f'model_reasoning_effort = {toml_string(entry["effort"])}',
        'daybreak = true',
        '',
    ])


def outputs(roles, out):
    files = {}
    for role in roles:
        for entry in role['models']:
            if not has_native_file(role):
                continue
            if entry['provider'] == 'claude':
                files[out / 'claude' / 'agents' / f'{role["id"]}.md'] = claude_agent(role, entry)
            else:
                files[out / 'codex' / 'agents' / f'{role["id"]}.toml'] = codex_agent(role, entry)
        if 'profile' in role:
            files[out / 'codex' / f'{role["profile"]}.config.toml'] = codex_profile(role)
    return files


def cell(text):
    return text.replace('|', '\\|').replace('\n', ' ')


def role_table(roles):
    rows = [
        '| Role | Purpose | Provider · model · effort | Layer | Authority | Alternates (explicit, record why) |',
        '| --- | --- | --- | --- | --- | --- |',
    ]
    for role in roles:
        models = ' **and** '.join(model_text(entry) for entry in role['models'])
        if 'launch' in role:
            models += f', Daybreak Blue via `codex --profile {role["profile"]}`'
        layer = role['layer'] + (f' ({role["launch"]})' if 'launch' in role else '')
        alternates = '<br>'.join(f'{model_text(entry)}: {entry["when"]}' for entry in role.get('alternates', []))
        rows.append(f'| **{label(role)}** `{role["id"]}` | {cell(role["purpose"])} | {models} | {layer} '
                    f'| {role["authority"]} | {cell(alternates) or "—"} |')
    return '\n'.join(rows)


def roles_md(roles):
    parts = [
        '# Roster roles',
        '',
        f'<!-- {NOTICE} -->',
        '',
        'Copy the role\'s standing instructions verbatim into every brief. '
        'The source of truth is `roster/roles.toml` in the Orca Pod repository.',
    ]
    for role in roles:
        parts += ['', f'## {label(role)} `{role["id"]}`', '', role['purpose'], '']
        for entry in role['models']:
            sandbox = f', sandbox `{entry["sandbox"]}`' if 'sandbox' in entry else ''
            parts.append(f'- Model: {model_text(entry)}{sandbox}')
        for entry in role.get('alternates', []):
            parts.append(f'- Alternate: {model_text(entry)}, when {entry["when"]}')
        parts.append(f'- Layer: {role["layer"]}; authority: {role["authority"]}')
        if 'launch' in role:
            parts.append(f'- Launch: {role["launch"]}, Codex profile `{role["profile"]}`')
        parts += ['', '```text', instructions(role), '```']
    return '\n'.join(parts) + '\n'


def skill_text(roles, current):
    head, sep, rest = current.partition(BEGIN)
    _, sep2, tail = rest.partition(END)
    if not sep or not sep2:
        fail(f'{SKILL.relative_to(ROOT)} lacks the generated-table markers')
    return f'{head}{BEGIN}\n{role_table(roles)}\n{END}{tail}'


def contain(files, out):
    """Refuse, before any write, a destination that escapes out or passes through a symlink below it."""
    root = out.resolve()
    for path in files:
        if not path.is_relative_to(out):
            refuse(path, f'outside {out}')
        current = out
        for part in path.relative_to(out).parts:
            current = current / part
            if current.is_symlink():
                refuse(path, f'{current} is a symlink')
        if not path.resolve().is_relative_to(root):
            refuse(path, f'resolves outside {root}')
        if path.exists() and not path.is_file():
            refuse(path, 'not a regular file')


def write(path, text):
    """Write only on change so a re-run touches nothing; return whether the file changed."""
    if path.exists() and path.read_text(encoding='utf-8') == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC | os.O_NOFOLLOW, 0o644)
    with open(descriptor, 'w', encoding='utf-8') as handle:
        handle.write(text)
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, default=DEFAULT_OUT,
                        help='directory receiving claude/agents and codex/agents (default: build/roster)')
    parser.add_argument('--check', action='store_true',
                        help='write nothing; exit 1 if the skills/roster tables are stale')
    args = parser.parse_args()
    roles = load()
    in_place = {SKILL: skill_text(roles, SKILL.read_text(encoding='utf-8')), ROLES_MD: roles_md(roles)}
    if args.check:
        stale = [path for path, text in in_place.items()
                 if not path.exists() or path.read_text(encoding='utf-8') != text]
        for path in stale:
            print(f'Stale: {path.relative_to(ROOT)}; run roster/generate.py', file=sys.stderr)
        if not stale:
            print('Roster tables are current.')
        return 1 if stale else 0
    out = args.out.expanduser().absolute()
    generated = outputs(roles, out)
    contain(generated, out)
    # The two in-repo tables are the only destinations outside --out.
    for path in in_place:
        if path.is_symlink() or path.resolve() != path:
            refuse(path, 'the in-repo table is or sits under a symlink')
    files = {**generated, **in_place}
    for path, text in files.items():
        shown = path.relative_to(ROOT) if path.is_relative_to(ROOT) else path
        print(f'{"wrote" if write(path, text) else "unchanged"} {shown}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
